"""gen_v13.py - the YACC1 video card v1.3 board (2026-10-22): v1.2's outline, X1 and placement on a 4-layer board
(In1.Cu = solid GND plane, In2.Cu = solid VCC plane), every signal routed anew by Freerouting, GND/VCC never routed
(every power pin is a through-hole pad on its plane). Follows the memory card v2.0 build (hardware/cards/memory/kicad/
v2.0: gen_relayout.py dsn/ses/stats, gen_standoff.py shuffle); build.sh runs it.

Run with KiCad's bundled Python (pcbnew), from this folder:
  gen_v13.py project                       -> video-v1.3.kicad_pro rules + video-v1.3.kicad_dru (signals 0.25 mm, 0.2 mm
                                              clearance, vias 0.8/0.4 mm; class Power = GND, VCC: not routed)
  gen_v13.py board <netlist> <out.pcb>     -> the unrouted board: v1.2 with every track and via removed, In1/In2 added
                                              with the two planes, JP2 + R15 placed, every pad on its schematic net
  gen_v13.py dsn <pcb> <out.dsn>           -> a 2-signal-layer copy (planes dropped) as Specctra DSN
  gen_v13.py shuffle <dsn> <seed> <out>    -> the DSN with its components in another order (seed 0: unchanged)
  gen_v13.py ses <pcb> <ses> <out.pcb>     -> the routing imported (Freerouting's F.Cu-B.Cu vias as through vias)
  gen_v13.py stats <pcb> <drc.json> [out.json]  -> unrouted / vias / length / copper DRC findings of a routed board
  gen_v13.py silk <pcb>                    -> the texts beside the new parts placed clear of each other (JP2's and
                                              R15's references, PWR0's moved off R15's pad, the DOTS label)
  gen_v13.py verify <netlist> <pcb>        -> every v1.3 change checked pin by pin in the schematic netlist and on the
                                              board's pads; no track on GND/VCC; the four copper layers; one plane each
"""
