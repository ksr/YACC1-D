def verify(netfile, pcb):
    nodes, comps = read_netlist(netfile)
    t = open(pcb).read()
    pads = {}
    for fp in top_forms(t):
        if not fp.startswith("(footprint"): continue
        ref = re.search(r'\(property "Reference" "([^"]+)"', fp).group(1)
        for m in re.finditer(r'\(pad "([^"]*)" .*?(?=\n\t\t\(pad |\Z)', fp, re.S):
            n = re.search(r'\(net "([^"]*)"\)', m.group(0)); pads[(ref, m.group(1))] = n.group(1) if n else None
    bad = 0
    for ref, pad, want in CHANGES:
        sch, brd = nodes.get((ref, pad)), pads.get((ref, pad), "(missing)")
        ok = sch == want and brd == want
        bad += not ok
        print("  %-5s %-3s schematic %-11s board %-11s %s" % (ref, pad, sch, brd, "ok" if ok else "WANT %s" % want))
    power = len(re.findall(r'\(segment[^()]*?(?:\([^()]*\)[^()]*?)*?\(net "(?:GND|VCC)"\)', t))
    layers = re.findall(r'\(\d+ "([^"]+\.Cu)" signal\)', t)
    zones = [z for z in top_forms(t) if z.startswith("(zone") and '(net "' in z]
    planes = sorted((re.search(r'\(net "([^"]+)"', z).group(1), re.search(r'\(layer "([^"]+)"', z).group(1)) for z in zones)
    print("  copper layers %s; planes %s; tracks on GND/VCC %d" % (layers, planes, power))
    bad += layers != ["F.Cu", "In1.Cu", "In2.Cu", "B.Cu"] or planes != [("GND", "In1.Cu"), ("VCC", "In2.Cu")] or power != 0
    print("verify: %s" % ("PASS" if not bad else "%d FAIL" % bad))
    return not bad


