HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", ".."))
P = "video-v1.3"
V12 = os.path.join(HERE, "..", "v1.2", "video-v1.2.kicad_pcb")
CLI = "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli"
RULES = dict(track=0.25, clearance=0.2, via=0.8, via_drill=0.4, annular=0.2, edge=0.5, hole_to_hole=0.25,
             hole_clearance=0.25)
DRU = """(version 1)
# generated by gen_v13.py: the video card v1.3 rules (2026-10-22), as the memory card v2.0's. The project's net classes
# say the same:
#   Default = every signal net: track 0.25 mm (10 mil), clearance 0.2 mm, via 0.8 / 0.4 mm
#   Power   = GND, VCC: NOT routed as tracks - every power pin is a through-hole pad on the In1 GND / In2 VCC plane
# Planes: 0.3 mm clearance (antipads), thermal reliefs 0.4 mm gap / 0.5 mm spokes. Copper to board edge 0.5 mm.
(rule "signal tracks 0.25 mm"
	(constraint track_width (min 0.25mm) (opt 0.25mm))
	(condition "A.Type == 'track'"))
(rule "clearance 0.2 mm"
	(constraint clearance (min 0.2mm)))
(rule "vias 0.8 / 0.4 mm"
	(constraint via_diameter (min 0.8mm))
	(constraint hole_size (min 0.4mm))
	(condition "A.Type == 'via'"))
(rule "plane antipads 0.3 mm"
	(constraint clearance (min 0.3mm))
	(condition "A.Type == 'zone' && (A.Layer == 'In1.Cu' || A.Layer == 'In2.Cu')"))
"""
# the parts v1.3 adds, as footprint text: (ref, library footprint file, at x y rot, pad -> net); the nets come from the
# schematic netlist anyway, these only place them
NEW = {"JP2": ("PinHeader_1x02_P2.54mm_Vertical", (179.7, 116.6, 90)),
       "R15": ("0207_7", (185.4, 116.81, 90))}
SILK = [("DOTS: ON=8", 177.6, 119.6, 0.8)]       # beside JP2: fitted = 8 dots a character (64 x 24), open = 6 (80 x 24)


def top_forms(text):
    forms, d, ins, start, j = [], 0, False, None, text.index("(") + 1
    while j < len(text):
        c = text[j]
        if ins:
            if c == "\\": j += 1
            elif c == '"': ins = False
        elif c == '"': ins = True
        elif c == "(":
            if d == 0: start = j
            d += 1
        elif c == ")":
            if d == 0: break
            d -= 1
            if d == 0: forms.append(text[start:j + 1])
        j += 1
    return forms


def read_netlist(path):
    """(ref, pad) -> net name, ref -> sheet path (from the schematic's kicadsexpr netlist)"""
    s = open(path).read()
    comps = {}
    for blk in re.split(r'\(comp\s*\n', s[:s.index("(libparts")] if "(libparts" in s else s)[1:]:
        ref = re.search(r'\(ref "([^"]+)"\)', blk).group(1)
        sp = re.search(r'\(sheetpath\s*\(names "[^"]*"\)\s*\(tstamps "([^"]*)"\)', blk)
        ts = re.search(r'\)\s*\(tstamps "([^"]*)"\)', blk[sp.end():] if sp else blk)
        comps[ref] = (sp.group(1) if sp else "/") + (ts.group(1) if ts else "")
    nodes = {}
    nets = s[s.index("(nets"):]
    for blk in re.split(r'\(net\s*\(code', nets)[1:]:
        name = re.search(r'\(name "([^"]*)"', blk).group(1)
        pins = re.findall(r'\(ref "([^"]+)"\)\s*\(pin "([^"]+)"', blk)
        if name.startswith("unconnected-") or len(pins) < 1:
            continue
        for r, p in pins:
            nodes[(r, p)] = name.split("/")[-1] if not name.startswith("Net-") else name
    return nodes, comps


def project():
    """the rules into video-v1.3.kicad_pro / .kicad_dru (classes Default and Power, as the memory card v2.0)"""
    pro = json.load(open(os.path.join(HERE, P + ".kicad_pro")))
    r = pro["board"]["design_settings"]["rules"]
    r.update(min_clearance=RULES["clearance"], min_track_width=RULES["track"], min_via_diameter=RULES["via"],
             min_through_hole_diameter=RULES["via_drill"], min_via_annular_width=RULES["annular"],
             min_copper_edge_clearance=RULES["edge"], min_hole_to_hole=RULES["hole_to_hole"],
             min_hole_clearance=RULES["hole_clearance"])
    ds = pro["board"]["design_settings"]
    ds["track_widths"] = [0.0, RULES["track"]]
    ds["via_dimensions"] = [{"diameter": 0.0, "drill": 0.0}, {"diameter": RULES["via"], "drill": RULES["via_drill"]}]
    base = pro["net_settings"]["classes"][0]
    base.update(track_width=RULES["track"], clearance=RULES["clearance"], via_diameter=RULES["via"],
                via_drill=RULES["via_drill"])
    power = dict(base, name="Power", priority=0, track_width=0.4)
    pro["net_settings"]["classes"] = [base, power]
    pro["net_settings"]["netclass_patterns"] = [{"netclass": "Power", "pattern": "GND"},
                                                {"netclass": "Power", "pattern": "VCC"}]
    json.dump(pro, open(os.path.join(HERE, P + ".kicad_pro"), "w"), indent=2)
    open(os.path.join(HERE, P + ".kicad_dru"), "w").write(DRU)
    print("project: Default %.2f mm / %.2f mm, vias %.1f / %.1f mm; class Power = GND, VCC (planes)" % (
        RULES["track"], RULES["clearance"], RULES["via"], RULES["via_drill"]))


def plane(net, layer, outline):
    pts = " ".join("(xy %g %g)" % p for p in outline)
    return ('(zone\n\t\t(net "%s")\n\t\t(layer "%s")\n\t\t(uuid "%s")\n\t\t(name "%s plane")\n\t\t(hatch edge 0.5)\n'
            '\t\t(priority 0)\n\t\t(connect_pads\n\t\t\t(clearance 0.3)\n\t\t)\n\t\t(min_thickness 0.25)\n\t\t(fill yes\n'
            '\t\t\t(thermal_gap 0.4)\n\t\t\t(thermal_bridge_width 0.5)\n\t\t\t(island_removal_mode 0)\n\t\t)\n'
            '\t\t(polygon\n\t\t\t(pts\n\t\t\t\t%s\n\t\t\t)\n\t\t)\n\t)' % (net, layer, uuid.uuid4(), net, pts))


def board(netfile, out):
    import pcbnew
    nodes, comps = read_netlist(netfile)
    src = open(V12).read().replace("video-v1.2", P)
    assert src.count('"YACC1 Video Card V1.2"') == 1
    src = src.replace('"YACC1 Video Card V1.2"', '"YACC1 Video Card V1.3"')
    src = src.replace('\t\t(2 "B.Cu" signal)', '\t\t(4 "In1.Cu" signal)\n\t\t(6 "In2.Cu" signal)\n\t\t(2 "B.Cu" signal)', 1)
    forms = top_forms(src)
    edge = [f for f in forms if f.startswith("(gr_") and '"Edge.Cuts"' in f]
    xy = [(float(a), float(b)) for f in edge for a, b in re.findall(r'\((?:start|end) ([-\d.]+) ([-\d.]+)\)', f)]
    x0, y0 = min(p[0] for p in xy), min(p[1] for p in xy)
    x1, y1 = max(p[0] for p in xy), max(p[1] for p in xy)
    outline = [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
    kept = [f for f in forms if not re.match(r"\((segment|via|arc)\b", f)]
    kept += [plane("GND", "In1.Cu", outline), plane("VCC", "In2.Cu", outline)]
    open(out, "w").write("(kicad_pcb\n\t" + "\n\t".join(kept) + "\n)\n")
    b = pcbnew.LoadBoard(out)
    FM = pcbnew.FromMM
    lib = os.path.join(HERE, P + "-eagle.pretty")
    for ref, (fpname, (x, y, rot)) in NEW.items():
        fp = pcbnew.FootprintLoad(lib, fpname)
        fp.SetFPIDAsString("%s-eagle:%s" % (P, fpname))
        fp.SetReference(ref)
        fp.SetPosition(pcbnew.VECTOR2I(FM(x), FM(y)))
        fp.SetOrientationDegrees(rot)
        fp.Reference().SetTextSize(pcbnew.VECTOR2I(FM(1.0), FM(1.0)))
        fp.Reference().SetTextThickness(FM(0.15))
        b.Add(fp)
    nets = {}

    def net(name):
        if name not in nets:
            ni = b.FindNet(name)
            if ni is None:
                ni = pcbnew.NETINFO_ITEM(b, name)
                b.Add(ni)
            nets[name] = ni
        return nets[name]

    values = {"Q2": "12MHz", "IC25": "2732 (chargen-v13)", "JP2": "DOTS 8=ON", "R15": "4.7K", "IC28": "74163"}
    n = 0
    for fp in b.GetFootprints():
        ref = fp.GetReference()
        if ref not in comps:
            raise SystemExit("board: %s is not in the schematic" % ref)
        fp.SetPath(pcbnew.KIID_PATH(comps[ref]))
        if ref in values:
            fp.SetValue(values[ref])
        for p in fp.Pads():
            if (ref, p.GetNumber()) in nodes:
                p.SetNet(net(nodes[(ref, p.GetNumber())])); n += 1
            else:
                p.SetNetCode(0)
    for s, x, y, size in SILK:
        t = pcbnew.PCB_TEXT(b)
        t.SetText(s); t.SetLayer(pcbnew.F_SilkS)
        t.SetTextSize(pcbnew.VECTOR2I(FM(size), FM(size))); t.SetTextThickness(FM(0.15))
        t.SetHorizJustify(pcbnew.GR_TEXT_H_ALIGN_LEFT)
        t.SetPosition(pcbnew.VECTOR2I(FM(x), FM(y)))
        b.Add(t)
    pcbnew.SaveBoard(out, b)
    refill(out)
    print("board %s: v1.2 placement, %d pads on nets, In1 GND / In2 VCC planes over %.1f x %.1f mm, JP2 + R15 placed" % (
        os.path.basename(out), n, x1 - x0, y1 - y0))


def refill(pcb):
    subprocess.run([CLI, "pcb", "drc", "--refill-zones", "--save-board", "-o", pcb + ".tmp.rpt", pcb], capture_output=True)
    if os.path.exists(pcb + ".tmp.rpt"):
        os.remove(pcb + ".tmp.rpt")


def dsn(pcb, out):
    """a two-signal-layer copy (the plane zones dropped, the inner layers removed) -> Specctra DSN"""
    import pcbnew
    sys.path.insert(0, os.path.join(ROOT, "tools", "kicad"))
    import kicad_route as KR
    t = open(pcb).read()
    keep = [f for f in top_forms(t) if not (f.startswith("(zone") and "(keepout" not in f)]
    d = os.path.dirname(os.path.abspath(out))
    tmp = os.path.join(d, "_dsn2l.kicad_pcb")
    open(tmp, "w").write("(kicad_pcb\n\t" + "\n\t".join(keep) + "\n)\n")
    shutil.copy(pcb[:-len(".kicad_pcb")] + ".kicad_pro", os.path.join(d, "_dsn2l.kicad_pro"))
    try:
        b = pcbnew.LoadBoard(tmp)
        b.SetCopperLayerCount(2)
        if not pcbnew.ExportSpecctraDSN(b, out):
            raise SystemExit("dsn: export failed")
    finally:
        for f in ("_dsn2l.kicad_pcb", "_dsn2l.kicad_pro", "_dsn2l.kicad_prl"):
            if os.path.exists(os.path.join(d, f)):
                os.remove(os.path.join(d, f))
    s = KR._inset_dsn_boundary(open(out).read())
    open(out, "w").write(s)
    print("dsn %s: layers %s, classes %s" % (os.path.basename(out), re.findall(r"\(layer (\S+)\s*\(type (\w+)\)", s),
                                             re.findall(r"\(class (\S+)", s)))


def shuffle(dsnfile, seed, out):
    """the DSN with its (placement ...) components in another order (seed 0 = unchanged): Freerouting 1.9 is
    deterministic for one file, the listing order changes its route (memory card v2.0, gen_standoff.shuffle)"""
    t = open(dsnfile).read()
    j = t.index("(placement") + len("(placement")
    comps, k = [], j
    while re.compile(r"\s*\(component\b").match(t, k):
        a = t.index("(component", k)
        depth, q = 0, a
        while True:
            if t[q] == "(": depth += 1
            elif t[q] == ")":
                depth -= 1
                if depth == 0: break
            q += 1
        comps.append(t[a:q + 1]); k = q + 1
    if int(seed):
        random.Random(int(seed)).shuffle(comps)
    open(out, "w").write(t[:j] + "".join("\n    " + c for c in comps) + t[k:])


def ses(pcb, sesfile, out):
    import pcbnew
    shutil.copy(pcb, out)
    b = pcbnew.LoadBoard(out)
    if not pcbnew.ImportSpecctraSES(b, sesfile):
        raise SystemExit("ses: ImportSpecctraSES failed")
    pcbnew.SaveBoard(out, b)
    t = open(out).read()
    open(out, "w").write(re.sub(r"^\t\(via (?:buried|blind)\b", "\t(via", t, flags=re.M))
    refill(out)


COSMETIC = {"silk_overlap", "silk_edge_clearance", "silk_over_copper", "text_height", "text_thickness",
            "lib_footprint_mismatch", "lib_footprint_issues", "courtyards_overlap", "missing_courtyard"}


def stats(pcb, drcfile, out=None):
    import pcbnew
    b = pcbnew.LoadBoard(pcb)
    T = pcbnew.ToMM
    L = collections.Counter(); nvia = 0
    for t in b.GetTracks():
        if t.Type() == pcbnew.PCB_VIA_T: nvia += 1
        else: L[b.GetLayerName(t.GetLayer())] += T(t.GetLength())
    d = json.load(open(drcfile))
    c = collections.Counter(v["type"] for v in d["violations"])
    copper = {k: n for k, n in c.items() if k not in COSMETIC and k != "items_not_allowed"}
    r = dict(unrouted=len(d.get("unconnected_items", [])), vias=nvia, length=round(sum(L.values())), copper=copper,
             cosmetic={k: n for k, n in c.items() if k in COSMETIC or k == "items_not_allowed"})
    print("%s: unrouted %d, vias %d, track %d mm (F.Cu %.0f, B.Cu %.0f), copper DRC %s" % (
        os.path.basename(pcb), r["unrouted"], nvia, r["length"], L.get("F.Cu", 0), L.get("B.Cu", 0), copper or "none"))
    if out:
        json.dump(r, open(out, "w"))
    return r


def silk(pcb):
    import pcbnew
    b = pcbnew.LoadBoard(pcb); FM = pcbnew.FromMM; V = pcbnew.VECTOR2I
    fp = {f.GetReference(): f for f in b.GetFootprints()}
    for ref, x, y, ang, just in (("JP2", 180.97, 114.2, 0, pcbnew.GR_TEXT_H_ALIGN_CENTER),
                                 ("R15", 187.3, 116.81, 90, pcbnew.GR_TEXT_H_ALIGN_CENTER),
                                 ("PWR0", 194.4, 115.3, 0, pcbnew.GR_TEXT_H_ALIGN_RIGHT)):
        r = fp[ref].Reference(); r.SetPosition(V(FM(x), FM(y))); r.SetTextAngleDegrees(ang); r.SetHorizJustify(just)
    for d in b.GetDrawings():
        if d.GetClass() == "PCB_TEXT" and d.GetText() == SILK[0][0]:
            d.SetTextSize(V(FM(0.8), FM(0.8))); d.SetTextThickness(FM(0.15)); d.SetPosition(V(FM(176.6), FM(121.2)))
    pcbnew.SaveBoard(pcb, b)


