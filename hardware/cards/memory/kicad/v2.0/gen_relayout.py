# board
def place_fp(fp, spec, pcbnew):
    """put a footprint where relayout_placements.py says: rotation, pad-bbox centre, pad 1 snapped to the X1 grid"""
    cx, cy, o = spec
    if isinstance(o, str):
        deg = RP.DIP_ROT[o] + (90 if fp.GetFPIDAsString().startswith("Package_DIP") else 0)
    else:
        deg = o
    FM, T = pcbnew.FromMM, pcbnew.ToMM
    fp.SetOrientationDegrees(deg % 360)
    fp.SetPosition(pcbnew.VECTOR2I(0, 0))
    pads = list(fp.Pads())
    xs = [T(p.GetPosition().x) for p in pads]
    ys = [T(p.GetPosition().y) for p in pads]
    ox, oy = cx - (min(xs) + max(xs)) / 2, cy - (min(ys) + max(ys)) / 2
    p1 = [p for p in pads if p.GetNumber() in ("1", "A")] or pads
    px, py = T(p1[0].GetPosition().x) + ox, T(p1[0].GetPosition().y) + oy
    gx, gy = RP.GRID_ORIGIN
    ox += round((px - gx) / RP.GRID) * RP.GRID + gx - px
    oy += round((py - gy) / RP.GRID) * RP.GRID + gy - py
    fp.SetPosition(pcbnew.VECTOR2I(FM(ox), FM(oy)))


def build(opt, netfile, out=None):
    import pcbnew
    from pcbnew import VECTOR2I
    O = RP.OPTIONS[opt]
    FM = pcbnew.FromMM
    P = lambda x, y: VECTOR2I(FM(x), FM(y))
    nodes, paths = GM.read_netlist(netfile)
    out = out or fname(opt)
    src = open(os.path.join(GM.V13, GM.OLD + ".kicad_pcb")).read()
    assert src.count('"%s"' % GM.TITLE_OLD) == 1
    src = src.replace('"%s"' % GM.TITLE_OLD, '"%s"' % GM.TITLE_NEW)
    forms = gen_cf.top_forms(src)
    kept = [f for f in forms if not re.match(r"\((segment|via|arc)\b", f)]
    dropped = len(forms) - len(kept)
    open(out, "w").write("(kicad_pcb\n\t" + "\n\t".join(kept) + "\n)\n")
    b = pcbnew.LoadBoard(out)
    fps = {f.GetReference(): f for f in b.GetFootprints()}
    x1_at = (fps["X1"].GetPosition().x, fps["X1"].GetPosition().y, fps["X1"].GetOrientationDegrees())
    old_at = {r: (f.GetPosition().x, f.GetPosition().y) for r, f in fps.items()}

    nets = {}

    def net(name):
        if name not in nets:
            ni = b.FindNet(name)
            if ni is None:
                ni = pcbnew.NETINFO_ITEM(b, name)
                b.Add(ni)
            nets[name] = ni
        return nets[name]

    for ref, (value, symid, fpid, note) in NL.PARTS.items():
        lib, name = fpid.split(":")
        fp = pcbnew.FootprintLoad(os.path.join(GM.KFP, lib + ".pretty"), name)
        if fp is None:
            raise SystemExit("board: footprint %s not found" % fpid)
        fp.SetFPIDAsString(fpid)
        fp.SetReference(ref)
        fp.SetValue(value)
        fp.SetField("Description", note)
        b.Add(fp)
        fps[ref] = fp
    for ref, fp in fps.items():
        if ref in NL.REMOVED:
            # C20-C23: removed from the schematic after these option boards were made (Ken 2026-09-24); the option
            # boards are the review record from before, so they keep them as the built board has them (path, GND /
            # VCC pads); finish_v2.py make takes them off the final board
            got = {p.GetNumber(): p.GetNetname() for p in fp.Pads()}
            if got != NL.REMOVED_NETS:
                raise SystemExit("board: removed part %s has pads %s on the built board" % (ref, got))
            continue
        if ref not in paths:
            raise SystemExit("board: %s is not in the schematic" % ref)
        fp.SetPath(pcbnew.KIID_PATH("/" + "/".join(x for x in paths[ref].split("/") if x and x != GM.ROOT_UUID)))
        for p in fp.Pads():
            if p.GetNumber() == "":
                continue
            if (ref, p.GetNumber()) in nodes:
                p.SetNet(net(nodes[(ref, p.GetNumber())]))
            elif p.GetNetname():
                raise SystemExit("board: %s.%s is on %s but has no pin in the schematic" % (ref, p.GetNumber(),
                                                                                            p.GetNetname()))
    missing = sorted(r for r in fps if r != "X1" and r not in O["place"])
    extra = sorted(r for r in O["place"] if r not in fps)
    if missing or extra:
        raise SystemExit("option %s: parts not placed %s, unknown %s" % (opt, missing, extra))
    if "X1" in O["place"]:
        raise SystemExit("option %s: X1 stays where the built card has it" % opt)
    for ref, spec in O["place"].items():
        place_fp(fps[ref], spec, pcbnew)
    # reference texts of the KiCad-library parts: small, beside the body (the Eagle parts keep theirs)
    for ref in NL.PARTS:
        fp = fps[ref]
        fld = fp.Reference()
        fld.SetTextSize(VECTOR2I(FM(1.0), FM(1.0)))
        fld.SetTextThickness(FM(0.15))
    # the built card's silkscreen labels that belong to a part move with it
    delta = {r: (fps[r].GetPosition().x - old_at[r][0], fps[r].GetPosition().y - old_at[r][1]) for r in old_at}
    LABELS = {"ROM": "U$1", "RAM": "U$1", "0X8000": "U$1", "0XF000": "U$1", "-BUS-EN": "JP1", "Gnd": "JP1"}
    for d in b.GetDrawings():
        if d.GetClass() != "PCB_TEXT":
            continue
        t = d.GetText()
        if t in LABELS:
            dx, dy = delta[LABELS[t]]
            d.SetPosition(VECTOR2I(d.GetPosition().x + dx, d.GetPosition().y + dy))
        elif t in O.get("texts", {}):
            d.SetPosition(P(*O["texts"][t]))

    def text(s, x, y, size=1.0, angle=0, layer=pcbnew.F_SilkS, just=pcbnew.GR_TEXT_H_ALIGN_LEFT):
        t = pcbnew.PCB_TEXT(b)
        t.SetText(s)
        t.SetLayer(layer)
        t.SetTextSize(VECTOR2I(FM(size), FM(size)))
        t.SetTextThickness(FM(max(0.15, size * 0.15)))
        t.SetHorizJustify(just)
        t.SetTextAngleDegrees(angle)
        t.SetPosition(P(x, y))
        b.Add(t)

    def rect(x0, y0, x1, y1, layer, dash=False, w=0.2):
        for (a, c, d_, e) in ((x0, y0, x1, y0), (x1, y0, x1, y1), (x1, y1, x0, y1), (x0, y1, x0, y0)):
            s = pcbnew.PCB_SHAPE(b)
            s.SetShape(pcbnew.SHAPE_T_SEGMENT)
            s.SetStart(P(a, c))
            s.SetEnd(P(d_, e))
            s.SetLayer(layer)
            s.SetWidth(FM(0.301 if dash else w))
            b.Add(s)

    JUST = {"l": pcbnew.GR_TEXT_H_ALIGN_LEFT, "c": pcbnew.GR_TEXT_H_ALIGN_CENTER, "r": pcbnew.GR_TEXT_H_ALIGN_RIGHT}
    for s, x, y, size, angle, just in O.get("silk", []):
        text(s, x, y, size, angle, just=JUST[just])
    # the TAODAN adapter (User.Drawings): strip + keep-low zone, from J2's pads
    j2 = fps["J2"]
    ys = sorted(pcbnew.ToMM(p.GetPosition().y) for p in j2.Pads())
    xs = sorted(pcbnew.ToMM(p.GetPosition().x) for p in j2.Pads())
    c = (xs[0] + xs[-1]) / 2
    m = (ys[0] + ys[-1]) / 2
    keep = (c - RP.LOW_SIDE, ys[0] - RP.LOW_BEYOND, c + RP.LOW_SIDE, ys[-1] + RP.LOW_BEYOND)
    rect(*keep, pcbnew.Dwgs_User, dash=True)
    rect(c - 4.0, m - RP.TAODAN_LEN / 2, c + 4.0, m + RP.TAODAN_LEN / 2, pcbnew.Dwgs_User, w=0.3)
    text("Option %s: %s" % (opt.upper(), O["title"]), 20.0, 7.0, 1.5, 0, pcbnew.Dwgs_User)
    text("Solid: TAODAN CF-IDE40 on J2 (70 mm, standing up); dashed: keep-low zone (nothing over ~8 mm)",
         20.0, 128.0, 1.2, 0, pcbnew.Dwgs_User)
    # planes: thermal reliefs and antipads of the re-layout rules
    for z in b.Zones():
        if z.GetIsRuleArea() or z.GetNetname() not in ("GND", "VCC"):
            continue
        z.SetLocalClearance(FM(RULES["plane_clearance"]))
        z.SetThermalReliefGap(FM(RULES["thermal_gap"]))
        z.SetThermalReliefSpokeWidth(FM(RULES["thermal_spoke"]))
        z.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL)
    fx = fps["X1"]
    assert (fx.GetPosition().x, fx.GetPosition().y, fx.GetOrientationDegrees()) == x1_at
    pcbnew.SaveBoard(out, b)
    t = open(out).read()
    t = re.sub(r"\(width 0\.301\)(\s*)\(type (?:solid|default)\)", r"(width 0.3)\1(type dash)", t)
    open(out, "w").write(t)
    write_project(opt)
    print("board %s: %d footprints (%d placed, X1 kept), %d built copper items removed"
          % (os.path.basename(out), len(fps), len(O["place"]), dropped))


