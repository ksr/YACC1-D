# checks
TALL = GM.TALL             # parts taller than ~8 mm (LEDs, headers + shunts, the radial cap, X1)


def check(pcb, opt):
    """no body overlaps (courtyards; the Eagle parts: pads + silk/fab graphics), every pad 0.5 mm inside the edge, X1 on
    its built spot, nothing tall (TALL) and no IC in the TAODAN keep-low zone; reference texts of the parts clear of
    every pad"""
    import pcbnew
    b = pcbnew.LoadBoard(pcb)
    T = pcbnew.ToMM
    boxes = GM.body_boxes(b)
    probs = []
    refs = sorted(boxes)
    for i, a in enumerate(refs):
        for c in refs[i + 1:]:
            o = GM.overlap(boxes[a], boxes[c])
            if o:
                probs.append("%s / %s overlap %.2f x %.2f mm" % (a, c, o[0], o[1]))
    E = b.GetBoardEdgesBoundingBox()
    ex0, ey0, ex1, ey1 = T(E.GetX()), T(E.GetY()), T(E.GetRight()), T(E.GetBottom())
    pads = []
    for f in b.GetFootprints():
        ref = f.GetReference()
        for p in f.Pads():
            pb = p.GetBoundingBox()
            pads.append((ref, p.GetNumber(), pb))
            if ref == "X1":
                continue
            x0, y0, x1, y1 = T(pb.GetX()), T(pb.GetY()), T(pb.GetRight()), T(pb.GetBottom())
            if min(x0 - ex0, y0 - ey0, ex1 - x1, ey1 - y1) < 0.5:
                probs.append("%s pad %s within 0.5 mm of the board edge" % (ref, p.GetNumber()))
        bx = boxes[ref]
        if ref != "X1" and (bx[0] < ex0 or bx[1] < ey0 or bx[2] > ex1 + 0.01 or bx[3] > ey1):
            probs.append("%s body outside the board outline %s" % (ref, [round(v, 2) for v in bx]))
    # X1 exactly where the built card has it
    import re as _re
    built = open(os.path.join(GM.V13, GM.OLD + ".kicad_pcb")).read()
    m = _re.search(r'\(footprint "[^"]*FABC96R"[^\n]*\n(?:[^\n]*\n){0,6}?\s*\(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\)', built)
    fx = [f for f in b.GetFootprints() if f.GetReference() == "X1"][0]
    if m and (abs(float(m.group(1)) - T(fx.GetPosition().x)) > 1e-3 or abs(float(m.group(2)) - T(fx.GetPosition().y)) > 1e-3):
        probs.append("X1 moved")
    # keep-low zone of the adapter
    j2 = [f for f in b.GetFootprints() if f.GetReference() == "J2"][0]
    ys = sorted(T(p.GetPosition().y) for p in j2.Pads())
    xs = sorted(T(p.GetPosition().x) for p in j2.Pads())
    c = (xs[0] + xs[-1]) / 2
    keep = (c - RP.LOW_SIDE, ys[0] - RP.LOW_BEYOND, c + RP.LOW_SIDE, ys[-1] + RP.LOW_BEYOND)
    under = sorted(r for r, bx in boxes.items() if r != "J2" and GM.overlap(bx, keep))
    for r in under:
        if r in TALL or r.startswith("IC"):
            probs.append("%s in the TAODAN keep-low zone" % r)
    near = []
    for r in list(TALL) + [r for r in boxes if r.startswith("IC")]:
        if r in boxes and r != "J2":
            bx = boxes[r]
            dx = max(keep[0] - bx[2], bx[0] - keep[2], 0)
            dy = max(keep[1] - bx[3], bx[1] - keep[3], 0)
            near.append((round((dx * dx + dy * dy) ** 0.5, 1), r))
    # reference texts on pads
    onpad = []
    for f in b.GetFootprints():
        fld = f.Reference()
        if not fld.IsVisible():
            continue
        tb = fld.GetBoundingBox()
        for ref, num, pb in pads:
            if tb.Intersects(pb):
                onpad.append("%s on %s.%s" % (f.GetReference(), ref, num))
                break
    print("placement %s: %s" % (os.path.basename(pcb), "OK - no overlaps, pads 0.5 mm inside the edge, X1 as built, "
                                "keep-low zone clear of ICs and tall parts" if not probs else "%d problem(s)" % len(probs)))
    for x in probs:
        print("    ", x)
    print("    J2 pads x %.2f/%.2f, y %.2f-%.2f; keep-low zone x %.1f-%.1f, y %.1f-%.1f holds: %s"
          % (xs[0], xs[-1], ys[0], ys[-1], keep[0], keep[2], keep[1], keep[3], ", ".join(under) or "nothing"))
    print("    nearest tall parts / ICs to the keep-low zone: %s" % ", ".join("%s %.1f mm" % (r, d) for d, r in sorted(near)[:4]))
    print("    reference texts touching a pad: %d %s" % (len(onpad), onpad[:8]))
    return not probs


def airwire(pcb):
    """straight-line length of the signal nets' minimum spanning trees (GND/VCC excluded: planes), mm"""
    import pcbnew
    b = pcbnew.LoadBoard(pcb)
    T = pcbnew.ToMM
    pts = collections.defaultdict(list)
    for f in b.GetFootprints():
        for p in f.Pads():
            n = p.GetNetname()
            if n and n not in ("GND", "VCC") and not n.startswith("unconnected-("):
                pts[n].append((T(p.GetPosition().x), T(p.GetPosition().y)))
    tot, conns = 0.0, 0
    for n, ps in pts.items():
        if len(ps) < 2:
            continue
        inn, rest = [ps[0]], ps[1:]
        while rest:
            d, j = min((math.dist(a, c), j) for j, c in enumerate(rest) for a in inn)
            tot += d
            conns += 1
            inn.append(rest.pop(j))
    return tot, conns, len([n for n, ps in pts.items() if len(ps) >= 2])


