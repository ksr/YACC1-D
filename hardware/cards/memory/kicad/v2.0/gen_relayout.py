#!/usr/bin/env python3
"""gen_relayout.py - the RE-LAYOUT boards of the YACC1 memory card v2.0 (2026-09-24): the whole card placed again from
scratch with the CF section designed in, and a trial autoroute of each placement option.

Ken's decision (2026-09-24): keep the circuit (the v2.0 netlist exactly: the built card v1.3 incl. IC15 + the CF
section), discard the built card's placement and copper. Kept from the built card: the board outline, the bus connector
X1 (position, orientation, its mounting holes; the card plugs into the same backplane), the 4-layer stack-up with the
solid In1 GND and In2 VCC planes (their outlines too). Signals on F.Cu and B.Cu only; every IC power pin reaches its
plane through its own through-hole pad (thermal relief); no power track is routed.

Run with KiCad's bundled Python (pcbnew); build.sh does, in this order per option:

  gen_relayout.py board <opt> <schematic .net>      -> options-top-edge-J2/memory-v2.0-relayout-<opt>.kicad_pcb (+ .kicad_pro,
                                                       .kicad_dru; the top-edge record since the standoff decision)
        the built board with every track and via removed; every pad on its v2.0 schematic net (as gen_mem_v2.py board);
        the CF footprints added; EVERY part except X1 placed from relayout_placements.py; the built card's silkscreen
        labels moved with their parts (U$1 block labels, JP1 labels), title V2.0, "CF: P8/P9" beside J2, LED/jumper
        labels; the TAODAN adapter strip + keep-low zone on User.Drawings; the planes' thermal reliefs; design rules
        (RULES below) in the project and in the .kicad_dru. C20-C23 (removed from the circuit on 2026-09-24, after
        these boards were made) stay on them as the built board has them: the option boards are the pre-removal review
        record (check_netlist.py --records, build.sh parity_new ... record)
  gen_relayout.py refill <pcb>                      -> the planes refilled (every new pad on GND/VCC gets its relief)
  gen_relayout.py check <pcb> <opt>                 -> placement check (overlaps, edge, keep-low zone, X1 = built)
  gen_relayout.py review <pcb> <out> render|plot    -> review copies (gen_mem_v2.py review_copy)
  gen_relayout.py dsn <pcb> <dsn>                   -> Specctra DSN of a TWO-signal-layer copy (the planes carry
                                                       GND/VCC: their net class Power is not routed, -inc Power)
  gen_relayout.py ses <pcb> <ses> <out>             -> the trial-routed board (Freerouting's copper on the 4-layer board)
  gen_relayout.py stats <pcb> <drc.json> [<opt>]    -> the trial-route numbers (unrouted, vias, length, DRC copper)
"""
