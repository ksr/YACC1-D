def dsn(pcb, out):
    """a two-signal-layer copy (the plane zones dropped, the inner layers removed) -> Specctra DSN for Freerouting; the
    routing boundary inset 0.35 mm (Freerouting's own edge clearance + 0.35 = the 0.5 mm rule)"""
    import pcbnew
    sys.path.insert(0, os.path.join(GM.ROOT, "tools", "kicad"))
    import kicad_route as KR
    t = open(pcb).read()
    forms = gen_cf.top_forms(t)
    keep = [f for f in forms if not (f.startswith("(zone") and "(keepout" not in f)]
    d = os.path.dirname(os.path.abspath(out))
    tmp = os.path.join(d, "_dsn2l.kicad_pcb")
    open(tmp, "w").write("(kicad_pcb\n\t" + "\n\t".join(keep) + "\n)\n")
    pro = pcb[:-len(".kicad_pcb")] + ".kicad_pro"
    import shutil
    shutil.copy(pro, os.path.join(d, "_dsn2l.kicad_pro"))
    try:
        b = pcbnew.LoadBoard(tmp)
        b.SetCopperLayerCount(2)
        if not pcbnew.ExportSpecctraDSN(b, out):
            raise SystemExit("dsn: export failed")
    finally:
        for f in ("_dsn2l.kicad_pcb", "_dsn2l.kicad_pro", "_dsn2l.kicad_prl"):
            if os.path.exists(os.path.join(d, f)):
                os.remove(os.path.join(d, f))
    s = KR._inset_dsn_boundary(open(out).read())
    open(out, "w").write(s)
    layers = re.findall(r"\(layer (\S+)\s*\(type (\w+)\)", s)
    classes = re.findall(r"\(class (\S+)", s)
    print("dsn %s: layers %s, classes %s" % (os.path.basename(out), layers, classes))


def ses(pcb, sesfile, out):
    import pcbnew
    import shutil
    shutil.copy(pcb, out)
    b = pcbnew.LoadBoard(out)
    if not pcbnew.ImportSpecctraSES(b, sesfile):
        raise SystemExit("ses: ImportSpecctraSES failed")
    pcbnew.SaveBoard(out, b)
    ntrk = sum(1 for t in b.GetTracks() if t.Type() == pcbnew.PCB_TRACE_T)
    nvia = sum(1 for t in b.GetTracks() if t.Type() == pcbnew.PCB_VIA_T)
    # the session's F.Cu-B.Cu vias come in as "buried" on the 4-layer board: they are through vias (fixed
    # 2026-09-24; the three committed trial routes of 2cae926 still carry the buried type, finish_v2.py make fixes it)
    t = open(out).read()
    nb = len(re.findall(r"^\t\(via (?:buried|blind)\b", t, re.M))
    open(out, "w").write(re.sub(r"^\t\(via (?:buried|blind)\b", "\t(via", t, flags=re.M))
    print("ses -> %s: %d track segments, %d vias (%d imported as buried -> through)" % (os.path.basename(out), ntrk,
                                                                                      nvia, nb))


COSMETIC = {"silk_overlap", "silk_edge_clearance", "silk_over_copper", "text_height", "text_thickness",
            "lib_footprint_mismatch", "lib_footprint_issues", "courtyards_overlap", "missing_courtyard"}


def stats(pcb, drcfile, opt=None):
    import pcbnew
    b = pcbnew.LoadBoard(pcb)
    T = pcbnew.ToMM
    L = collections.Counter()
    nvia = 0
    widths = collections.Counter()
    for t in b.GetTracks():
        if t.Type() == pcbnew.PCB_VIA_T:
            nvia += 1
        else:
            L[b.GetLayerName(t.GetLayer())] += T(t.GetLength())
            widths[round(T(t.GetWidth()), 3)] += 1
    d = json.load(open(drcfile))
    # X1's two mounting holes sit inside X1's own via keepout (the converted Eagle footprint): the built card's DRC
    # has the same two items; they are not copper
    x1 = lambda v: v["type"] == "items_not_allowed" and all(" of X1" in i["description"] for i in v["items"])
    inherited = sum(1 for v in d["violations"] if x1(v))
    c = collections.Counter(v["type"] for v in d["violations"] if not x1(v))
    copper = {k: n for k, n in c.items() if k not in COSMETIC}
    unr = len(d.get("unconnected_items", []))
    aw, conns, nn = airwire(pcb)
    print("trial route %s:\n  unrouted connections after Freerouting: %d\n  vias: %d\n  track length: %.0f mm "
          "(F.Cu %.0f, B.Cu %.0f; placement airwire %.0f mm over %d connections)\n  track widths (mm: segments): %s\n"
          "  DRC copper violations: %s\n  DRC inherited: %d (X1's mounting holes in X1's own keepout, as on the built "
          "card)\n  DRC cosmetic (silkscreen, Eagle library texts): %s"
          % (os.path.basename(pcb), unr, nvia, sum(L.values()), L.get("F.Cu", 0), L.get("B.Cu", 0), aw, conns,
             dict(widths), copper or "none", inherited, dict(sorted((k, n) for k, n in c.items() if k in COSMETIC))))
    for u in d.get("unconnected_items", []):
        print("    unrouted: %s" % " - ".join(i["description"] for i in u["items"]))
    return dict(unrouted=unr, vias=nvia, length=round(sum(L.values())), copper=copper)


