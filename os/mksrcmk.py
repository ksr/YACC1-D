"""mksrcmk.py - the Makefiles that /BIN/MAKE reads in the disk's /SRC (2026-11-03), from the tree, so they never
drift from the sources or from os/Makefile's flags:

  /SRC/os/commands/Makefile                 every /BIN command from its C (asm.c is ASMC), make install -> /BIN
  /SRC/os/commands-asm/Makefile             ASM, the assembler from its own assembly, make install -> /BIN/ASM
  /SRC/software/compiler/c/target/Makefile  CC1 .. CC9, the native compiler's passes, make install -> /LIB/CC
  /SRC/Makefile                             all three, one after the other (a recipe cds and runs make again)

  mksrcmk.py OUTDIR      writes them under OUTDIR at their /SRC paths (os/Makefile puts them on the disk)

The flags are os/Makefile's: a /BIN command --org 0x5000 --os, a pass --org 0x5000 --os --stack 0xCFFF --xisa
(tests/native/selfhost.py builds the passes, ASMC, CC and ASM on the emulated machine with them and compares them
with the host's byte for byte). A rule's prerequisites are its source and the files it #includes from beside it
(../lib_fs.c ...); y1lib.c comes from /LIB. Y1/OS keeps no file dates: make builds what is missing (man make).
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PASSN = "lex parse decl calls layout stmt sema emit final".split()   # os/Makefile PASSN: CC1 .. CC9
BFLAGS = "--org 0x5000 --os"
PFLAGS = "--org 0x5000 --os --stack 0xCFFF --xisa"
# commands the native compiler cannot build yet (2026-11-03): not in all or install, /BIN keeps the Mac's builds
NATIVE_NO = {"HELP": "its text is over cc1's string pool (STRPOOL 1800)",
             "KERMIT": "kermit_io.c's byte table is over cc3's NODES_MAX"}
HEAD = "# GENERATED by os/mksrcmk.py - Y1/OS keeps no file dates: make builds what is missing, make -B NAME rebuilds\n"


def includes(path, seen=None):
    """the files path #includes, as written (relative to path's directory), except the library's y1lib.c"""
    d = os.path.dirname(path)
    out = []
    for m in re.finditer(r'^#include "([^"]+)"', open(path, encoding="latin1").read(), re.M):
        f = m.group(1)
        if f != "y1lib.c" and os.path.exists(os.path.join(d, f)): out.append(f)
    return out


def rules(names, flags_var):
    """(NAME, source) pairs -> the rule lines: NAME: source + its includes / cc / asm"""
    t = []
    for name, src, path in names:
        t += ["%s: %s" % (name, " ".join([src] + includes(path))),
              "\tcc $< -o $@.ASM $(%s)" % flags_var,
              "\tasm $@.ASM", ""]
    return t


def install(names, where):
    return ["install: all"] + ["\tcp %s %s/%s" % (n, where, n) for n in names] + [""]


def write(outdir, rel, lines):
    p = os.path.join(outdir, rel, "Makefile")
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w").write("\n".join(lines) + "\n")


def main():
    if len(sys.argv) != 2: sys.exit(__doc__)
    out = sys.argv[1]
    # /BIN's commands from C
    cdir = os.path.join(HERE, "commands")
    cmds = []
    for f in sorted(os.listdir(cdir)):
        if f.endswith(".c"):
            n = f[:-2].upper()
            cmds.append(("ASMC" if n == "ASM" else n, f, os.path.join(cdir, f)))
    built = [n for n, _, _ in cmds if n not in NATIVE_NO]
    write(out, "os/commands", [HEAD.rstrip(),
          "# /BIN's commands from their C: make NAME (cc, then asm) builds NAME here, make install copies all to /BIN"] +
          ["# not in all: %s (%s)" % (n, why) for n, why in sorted(NATIVE_NO.items())] +
          ["CFLAGS = " + BFLAGS, "",
          "all: " + " ".join(built), ""] + rules(cmds, "CFLAGS") + install(built, "/BIN"))
    # /BIN/ASM from its assembly
    write(out, "os/commands-asm", [HEAD.rstrip(),
          "# /BIN/ASM, the assembler in YACC1 assembly, assembled by the assembler that is in /BIN now", "",
          "all: ASM", "",
          "ASM: asm.asm asmtab.inc", "\tasm asm.asm ASM", ""] + install(["ASM"], "/BIN"))
    # the compiler's passes
    tdir = os.path.join(ROOT, "software/compiler/c/target")
    passes = [("CC%d" % (i + 1), n + ".c", os.path.join(tdir, n + ".c")) for i, n in enumerate(PASSN)]
    write(out, "software/compiler/c/target", [HEAD.rstrip(),
          "# the native C compiler's nine passes, CC1 .. CC9 (cc runs /LIB/CC/CC1, each EXECs the next);",
          "# make install copies them to /LIB/CC: build and try them first, a bad pass stops cc",
          "PFLAGS = " + PFLAGS, "",
          "all: " + " ".join(n for n, _, _ in passes), ""] + rules(passes, "PFLAGS") + install([n for n, _, _ in passes], "/LIB/CC"))
    # everything
    dirs = ["/SRC/os/commands", "/SRC/os/commands-asm", "/SRC/software/compiler/c/target"]
    top = [HEAD.rstrip(), "# every program on the disk from /SRC: each directory's make, one after the other", ""]
    for t, arg in (("all", ""), ("install", " install")):
        top.append("%s:" % t)
        for d in dirs: top += ["\tcd " + d, "\tmake" + arg]
        top += ["\tcd /SRC", ""]
    write(out, "", top)


if __name__ == "__main__":
    main()
