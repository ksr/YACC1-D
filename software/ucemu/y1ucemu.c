/* ---- -G REV (2026-10-11): the video card at gate level -------------------------------------------------------
 * videogate.h is generated by software/gatemodel from the card's KiCad netlist with the bench reworks as netlist
 * edits: the bus path (IC18's block compare gated by -VMA, the ADDR11/ADDR0 decode in IC1/IC19/IC20/IC27, the E
 * one-shot IC26/IC27/R1/C1) evaluated for every combination of the bus inputs it reaches. Each step looks its decode
 * up from the address bus, -VMA, -MEM-RD and -MEM-WR: which of the display RAM's bus port (IC15), the 6845 (IC17)
 * and the JP1 latch (IC2) drives DATA0..7 or takes a write. The RAM's contents stay in mem[$D000..], the 6845's
 * registers in videomodel.h's vid, so -V, -W, vidsim and the debugger see the card as before. Bus events on the
 * card's side, each listed once per (event, opcode, step) as -w lists fights: contention (the card drives DATA0..7
 * together with another driver, whatever the values, or two of its own parts at once), a CPU read that finds
 * DATA0..7 undriven while the card is selected (the 6845's write-only address register, an empty socket), a read of
 * the latch whose inputs float, and the generator's own (an undefined chip select, a fight inside the card). */
